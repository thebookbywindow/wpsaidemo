export function isChineseSiteLocale(locale) {
  return `${locale ?? ''}`.toLowerCase().startsWith('zh')
}

export function translateHelpCenterLabel(sourceLabel, locale) {
  const source = `${sourceLabel ?? ''}`.trim()
  if (!source || isChineseSiteLocale(locale)) {
    return source
  }

  return HELP_CENTER_LABELS_EN[source] ?? source
}
