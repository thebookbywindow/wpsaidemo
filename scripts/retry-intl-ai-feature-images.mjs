/**
 * Retry missing intl-ai feature images from INTL_AI_FEATURE_META.sourceImageUrl.
 * Uses curl.exe (more reliable than fetch under CDN rate limits on Windows).
 *
 * Usage: node scripts/retry-intl-ai-feature-images.mjs
 */
import { spawn } from 'node:child_process'
import { access, mkdir, writeFile } from 'node:fs/promises'
import { dirname, extname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { INTL_AI_FEATURE_META } from '../src/data/intlAiFeatureMeta.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = join(ROOT, 'public', 'images', 'intl-ai-features')
const OUT_DATA = join(ROOT, 'src', 'data', 'intlAiFeatureMeta.js')
const CONCURRENCY = 3
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'

function extensionFromUrl(url) {
  try {
    const pathExt = extname(new URL(url).pathname).toLowerCase()
    if (['.png', '.jpg', '.jpeg', '.webp', '.gif'].includes(pathExt)) return pathExt
  } catch {
    /* ignore */
  }
  return '.jpg'
}

async function fileExists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

function curlDownload(url, dest) {
  return new Promise((resolve, reject) => {
    const child = spawn(
      'curl.exe',
      [
        '-fsSL',
        '--retry',
        '3',
        '--retry-delay',
        '1',
        '-A',
        UA,
        '-o',
        dest,
        url,
      ],
      { stdio: ['ignore', 'ignore', 'pipe'] },
    )
    let err = ''
    child.stderr.on('data', (chunk) => {
      err += chunk.toString()
    })
    child.on('close', (code) => {
      if (code === 0) resolve()
      else reject(new Error(err.trim() || `curl exit ${code}`))
    })
  })
}

async function mapPool(items, limit, worker) {
  const results = new Array(items.length)
  let next = 0
  async function run() {
    while (next < items.length) {
      const i = next++
      results[i] = await worker(items[i], i)
    }
  }
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, () => run()),
  )
  return results
}

function toJsModule(metaById) {
  const sorted = Object.keys(metaById)
    .sort()
    .reduce((acc, id) => {
      acc[id] = metaById[id]
      return acc
    }, {})
  return `/** Auto-generated by scripts/scrape-intl-ai-feature-meta.mjs — do not edit by hand. */\nexport const INTL_AI_FEATURE_META = ${JSON.stringify(sorted, null, 2)}\n`
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true })
  const meta = structuredClone(INTL_AI_FEATURE_META)

  const byImageUrl = new Map()
  for (const [id, entry] of Object.entries(meta)) {
    if (!entry?.sourceImageUrl) continue
    const ext = extensionFromUrl(entry.sourceImageUrl)
    const dest = join(OUT_DIR, `${id}${ext}`)
    const publicPath = `/images/intl-ai-features/${id}${ext}`
    if (entry.imageSrc && (await fileExists(join(ROOT, 'public', entry.imageSrc)))) {
      continue
    }
    if (await fileExists(dest)) {
      entry.imageSrc = publicPath
      continue
    }
    if (!byImageUrl.has(entry.sourceImageUrl)) byImageUrl.set(entry.sourceImageUrl, [])
    byImageUrl.get(entry.sourceImageUrl).push(id)
  }

  const jobs = [...byImageUrl.entries()]
  console.log(`Retrying ${jobs.length} unique image URLs…`)

  let ok = 0
  let fail = 0
  await mapPool(jobs, CONCURRENCY, async ([imageUrl, ids]) => {
    const ext = extensionFromUrl(imageUrl)
    try {
      const tmp = join(OUT_DIR, `_tmp_${ids[0]}${ext}`)
      await curlDownload(imageUrl, tmp)
      for (const id of ids) {
        const dest = join(OUT_DIR, `${id}${ext}`)
        const { copyFile, rename } = await import('node:fs/promises')
        if (id === ids[0]) await rename(tmp, dest)
        else await copyFile(join(OUT_DIR, `${ids[0]}${ext}`), dest)
        meta[id].imageSrc = `/images/intl-ai-features/${id}${ext}`
      }
      ok += 1
      console.log(`OK  ${ids[0]}${ext} ×${ids.length}`)
    } catch (err) {
      fail += 1
      console.error(`FAIL ${ids[0]}: ${err.message}`)
    }
  })

  await writeFile(OUT_DATA, toJsModule(meta), 'utf8')
  const withImg = Object.values(meta).filter((e) => e.imageSrc).length
  console.log(`\nWrote ${OUT_DATA}`)
  console.log(`retry ok=${ok} fail=${fail} | with imageSrc=${withImg}/${Object.keys(meta).length}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
