import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawn } from 'node:child_process'
import { INTL_AI_FEATURE_META } from '../src/data/intlAiFeatureMeta.js'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = join(ROOT, 'public', 'images', 'intl-ai-features')
const IMAGE_URL = 'https://aipal.wps.com/_nuxt/features-chat.PeNbeUg2.png'
const IDS = ['aipal', 'dbsheet-aipal']

function curlDownload(url, dest) {
  return new Promise((resolve, reject) => {
    const child = spawn(
      'curl.exe',
      ['-fsSL', '--retry', '3', '-o', dest, url],
      { stdio: ['ignore', 'ignore', 'pipe'] },
    )
    let err = ''
    child.stderr.on('data', (c) => {
      err += c.toString()
    })
    child.on('close', (code) =>
      code === 0 ? resolve() : reject(new Error(err || `exit ${code}`)),
    )
  })
}

mkdirSync(OUT_DIR, { recursive: true })
const primary = join(OUT_DIR, 'aipal.png')
await curlDownload(IMAGE_URL, primary)

const meta = structuredClone(INTL_AI_FEATURE_META)
for (const id of IDS) {
  const dest = join(OUT_DIR, `${id}.png`)
  if (id !== 'aipal') copyFileSync(primary, dest)
  meta[id] = {
    description:
      meta[id]?.description || 'AIPal | The Next-Gen Web All-in-One Copilot',
    imageSrc: `/images/intl-ai-features/${id}.png`,
    sourceImageUrl: IMAGE_URL,
  }
}

const sorted = Object.keys(meta)
  .sort()
  .reduce((acc, key) => {
    acc[key] = meta[key]
    return acc
  }, {})

writeFileSync(
  join(ROOT, 'src', 'data', 'intlAiFeatureMeta.js'),
  `/** Auto-generated by scripts/scrape-intl-ai-feature-meta.mjs — do not edit by hand. */\nexport const INTL_AI_FEATURE_META = ${JSON.stringify(sorted, null, 2)}\n`,
)

console.log('OK', IDS.join(', '), '←', IMAGE_URL)
